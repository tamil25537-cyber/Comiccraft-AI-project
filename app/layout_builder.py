def build_comic_layout(image_paths: list, full_story: str, outline: list) -> list:
    """
    Organizes the generated images, story narration, and outline into a structured layout.

    Args:
        image_paths (list): List of paths to generated images.
        full_story (str): Full story text generated by Gemini Pro.
        outline (list): List of outline dictionaries.

    Returns:
        list: A list of dictionaries containing panel details for UI rendering and PDF export.
    """
    # Split the full story into individual panel segments
    raw_segments = full_story.split("**Panel")
    story_panels = [f"**Panel{panel}" for panel in raw_segments if panel.strip()]

    # If splitting didn't yield enough segments, fallback to splitting by outline length
    if len(story_panels) < len(outline):
        story_panels = []
        for p in outline:
            desc = p.get("scene_description", "") if isinstance(p, dict) else str(p)
            story_panels.append(f"**Panel**\n{desc}\n**NARRATION:** {desc}")

    # Build layout panel by panel
    layout = []
    for idx, (image, text, panel_info) in enumerate(zip(image_paths, story_panels, outline), start=1):
        lines = text.strip().splitlines()
        # Remove panel title line like "**Panel 1: Title**" if present
        clean_text = "\n".join(lines[1:]).strip() if len(lines) > 1 else text.strip()
        
        title_val = panel_info.get("title", f"Panel {idx}") if isinstance(panel_info, dict) else f"Panel {idx}"
        scene_desc = panel_info.get("scene_description", "") if isinstance(panel_info, dict) else ""

        layout.append({
            "panel": idx,
            "title": title_val,
            "image_path": image,
            "text": clean_text,
            "scene_description": scene_desc
        })

    return layout
